// Helper functions for retrieval
export function getAllOperators(): OperatorDetailedProfile[] {
  return BANGLADESH_OPERATORS;
}

export function getOperatorBySlug(slug: string): OperatorDetailedProfile | undefined {
  return BANGLADESH_OPERATORS.find((op) => op.slug.toLowerCase() === slug.toLowerCase() || op.id.toLowerCase() === slug.toLowerCase());
}

export function getOperatorById(id: string): OperatorDetailedProfile | undefined {
  return BANGLADESH_OPERATORS.find((op) => op.id.toLowerCase() === id.toLowerCase());
}

export function getRoutesByDivision(division: string): BusRoute[] {
  if (division.toLowerCase() === "all") return BANGLADESH_ROUTES;
  return BANGLADESH_ROUTES.filter(
    (r) =>
      r.fromDivision.toLowerCase() === division.toLowerCase() ||
      r.toDivision.toLowerCase() === division.toLowerCase()
  );
}
